public class switchcase {
public static void main(String[] args) {
    


    String menu = "00";

    switch(menu)
    {
        case "baru":
            System.out.println("Menu Baru");
            break;

        case "buka":
            System.out.println("Menu buka");
            break;

        default:
            System.out.println("Menu Invalid");
            break;




    }
}
}
